TRANSLATIONS.sort(key=lambda x: -len(x[0]))

text_re = re.compile(r'>([^<]+)<')
dry = '--dry-run' in sys.argv
counts = collections.Counter()
files_changed = []

for path in sorted(glob.glob('ja/products/*.html')):
    s = open(path, encoding='utf-8').read()
    def repl(m):
        t = m.group(1)
        for en, ja in TRANSLATIONS:
            if en in t:
                n = t.count(en)
                counts[en] += n
                t = t.replace(en, ja)
        return '>' + t + '<'
    new = text_re.sub(repl, s)
    if new != s:
        files_changed.append(path)
        if not dry:
            open(path, 'w', encoding='utf-8').write(new)

print(f"Files changed: {len(files_changed)}")
print(f"Total replacements: {sum(counts.values())}")
for en, n in counts.most_common():
    ja = dict(TRANSLATIONS)[en]
    print(f"  {n:4d}  {en!r} -> {ja!r}")
