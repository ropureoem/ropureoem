dry = '--dry-run' in sys.argv
counts = collections.Counter()
files_changed = []

for path in sorted(glob.glob('ru/products/*.html')):
    s = open(path, encoding='utf-8').read()
    def repl(m):
        t = m.group(1)
        for en, ru in TRANSLATIONS:
            if en in t:
                n = t.count(en)
                counts[en] += n
                t = t.replace(en, ru)
        return '>' + t + '<'
    new = text_re.sub(repl, s)
    if new != s:
        files_changed.append(path)
        if not dry:
            open(path, 'w', encoding='utf-8').write(new)

