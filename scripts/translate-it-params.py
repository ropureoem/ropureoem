TRANSLATIONS.sort(key=lambda x: -len(x[0]))
# Placeholder indirection: each match is first swapped for a \x00 token and
# only expanded to Italian after all keys have been scanned. An Italian
# translation can contain an English key ("Ceramica" contains "Ceramic",
# "post-carbone" contains "post-carbon"); without this, a plain sequential
# replace rescans inserted text and corrupts it ("Ceramicaa" /
# "post-carbonee", verified on RP-F02). Tokens never occur in source HTML.
def _ph(i):
    return '\x00IT%03d\x00' % i

text_re = re.compile(r'>([^<]+)<')
dry = '--dry-run' in sys.argv
counts = collections.Counter()
files_changed = []

for path in sorted(glob.glob('it/products/*.html')):
    s = open(path, encoding='utf-8').read()
    def repl(m):
        t = m.group(1)
        used = []
        for i, (en, it) in enumerate(TRANSLATIONS):
            if en in t:
                n = t.count(en)
                counts[en] += n
                t = t.replace(en, _ph(i))
                used.append(i)
        for i in used:
            t = t.replace(_ph(i), TRANSLATIONS[i][1])
        return '>' + t + '<'
    new = text_re.sub(repl, s)
    if new != s:
        files_changed.append(path)
        if not dry:
            open(path, 'w', encoding='utf-8').write(new)

print(f"Files changed: {len(files_changed)}")
print(f"Total replacements: {sum(counts.values())}")
for en, n in counts.most_common():
    it = dict(TRANSLATIONS)[en]
    print(f"  {n:4d}  {en!r} -> {it!r}")
if dry:
    print("DRY RUN - no files written")
else:
    print("Applied.")
    for f in files_changed:
        print("  ", f)
