# Longest first so longer phrases win over their substrings.
TRANSLATIONS.sort(key=lambda x: -len(x[0]))
# Placeholder indirection: each match is first swapped for a \x00 token and
# only expanded to Spanish after all keys have been scanned. A Spanish
# translation can contain an English key ("post-carbono" contains
# "post-carbon"); without this, a plain sequential replace rescans inserted
# text and corrupts it. Tokens never occur in source HTML.
def _ph(i):
    return '\x00ES%03d\x00' % i

# Pre-mask translations already present in the node (left by the build's TSV
# pass): an English key can be a substring of its own translation
# ('post-carbon' inside 'post-carbono', 'ambient' inside 'ambiente'), so a
# rule would re-fire on already-translated text and corrupt it
# ('post-carbonoo' — the 'post-carbonee' / 'Ceramicaa' class seen on
# RP-C07/RP-F02). A translation is masked only if it is not itself an
# English key and not a substring of any English key ('Beige' in
# 'Beige, gold ring'): masking one of those would break the English source
# before its own rule can match. Longest first so a long translation masks
# before its substring. Mask tokens never occur in source HTML.
_SOURCES = {en for en, _ in TRANSLATIONS}
_MASK = sorted({xx for _, xx in TRANSLATIONS
                if xx not in _SOURCES and not any(xx in en for en in _SOURCES)},
               key=len, reverse=True)
def _mask(t):
    masked = {}
    for j, xx in enumerate(_MASK):
        if xx in t:
            tok = '\x00M%03d\x00' % j
            t = t.replace(xx, tok)
            masked[tok] = xx
    return t, masked
def _unmask(t, masked):
    for tok, xx in masked.items():
        t = t.replace(tok, xx)
    return t

text_re = re.compile(r'>([^<]+)<')
dry = '--dry-run' in sys.argv
counts = collections.Counter()
files_changed = []

for path in sorted(glob.glob('es/products/*.html')):
    s = open(path, encoding='utf-8').read()
    def repl(m):
        t, masked = _mask(m.group(1))
        used = []
        for i, (en, es) in enumerate(TRANSLATIONS):
            if en in t:
                n = t.count(en)
                counts[en] += n
                t = t.replace(en, _ph(i))
                used.append(i)
        for i in used:
            t = t.replace(_ph(i), TRANSLATIONS[i][1])
        return '>' + _unmask(t, masked) + '<'
    new = text_re.sub(repl, s)
    if new != s:
        files_changed.append(path)
        if not dry:
            open(path, 'w', encoding='utf-8').write(new)

print(f"Files changed: {len(files_changed)}")
print(f"Total replacements: {sum(counts.values())}")
for en, n in counts.most_common():
    es = dict(TRANSLATIONS)[en]
    print(f"  {n:4d}  {en!r} -> {es!r}")
if dry:
    print("DRY RUN - no files written")
else:
    print("Applied.")
    for f in files_changed:
        print("  ", f)
