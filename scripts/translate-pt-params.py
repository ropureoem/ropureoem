# Longest first so longer phrases win over their substrings.
TRANSLATIONS.sort(key=lambda x: -len(x[0]))
# Pre-mask translations already present in the node (left by the build's TSV
# pass): an English key can be a substring of its own translation
# ('ambient' inside 'ambiente'), so a rule would re-fire on already-translated
# text and corrupt it ('ambientee' — the 'post-carbonee' / 'Ceramicaa' class
# seen on RP-C07/RP-F02). A translation is masked only if it is not itself
# an English key and not a substring of any English key ('Beige' in
# 'Beige, gold ring'): masking one of those would break the English source
# before its own rule can match. Longest first so a long translation masks
# before its substring. Mask tokens never occur in source HTML.
_SOURCES = {en for en, _ in TRANSLATIONS}
_MASK = sorted({xx for _, xx in TRANSLATIONS
                if xx not in _SOURCES and not any(xx in en for en in _SOURCES)},
               key=len, reverse=True)
def _mask(t):
    masked = {}
    for j, xx in enumerate(_MASK):
        if xx in t:
            tok = '\x00M%03d\x00' % j
            t = t.replace(xx, tok)
            masked[tok] = xx
    return t, masked
def _unmask(t, masked):
    for tok, xx in masked.items():
        t = t.replace(tok, xx)
    return t

text_re = re.compile(r'>([^<]+)<')
dry = '--dry-run' in sys.argv
counts = collections.Counter()
files_changed = []

for path in sorted(glob.glob('pt/products/*.html')):
    s = open(path, encoding='utf-8').read()
    def repl(m):
        t, masked = _mask(m.group(1))
        for en, pt in TRANSLATIONS:
            if en in t:
                n = t.count(en)
                counts[en] += n
                t = t.replace(en, pt)
        return '>' + _unmask(t, masked) + '<'
    new = text_re.sub(repl, s)
    if new != s:
        files_changed.append(path)
        if not dry:
            open(path, 'w', encoding='utf-8').write(new)

print(f"Files changed: {len(files_changed)}")
print(f"Total replacements: {sum(counts.values())}")
for en, n in counts.most_common():
    pt = dict(TRANSLATIONS)[en]
    print(f"  {n:4d}  {en!r} -> {pt!r}")
if dry:
    print("DRY RUN - no files written")
else:
    print("Applied.")
    for f in files_changed:
        print("  ", f)

